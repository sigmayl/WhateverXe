bool buildBrcConstantData(const BrcConstantParams &params, BrcConstantData &out) {
    if (!params.slices || !params.sliceCount || params.sliceCount > kBrcMaximumSlices ||
        !params.batchBytes || params.batchBytes >= 0xffff || (params.batchBytes & 3))
        return false;
    uint32_t previousEnd = 0;
    for (uint32_t i = 0; i < params.sliceCount; ++i) {
        const auto &slice = params.slices[i];
        const uint64_t end = uint64_t(slice.startOffset) + slice.commandsBytes;
        const uint64_t headerEnd = uint64_t(slice.sliceHeaderOffset) + 8 +
            ((uint64_t(slice.sliceHeaderBits) + 31) / 32) * 4;
        if (!slice.commandsBytes || !slice.sliceHeaderBits || slice.sliceHeaderBits >= 0xffff ||
            (slice.startOffset & 3) || (slice.commandsBytes & 3) ||
            (slice.sliceStateOffset & 3) || (slice.sliceHeaderOffset & 3) ||
            (slice.vdencWeightsOffset & 3) || slice.startOffset < previousEnd ||
            end > params.batchBytes || slice.sliceStateOffset < slice.startOffset ||
            uint64_t(slice.sliceStateOffset) + 52 > slice.sliceHeaderOffset ||
            headerEnd > slice.vdencWeightsOffset ||
            uint64_t(slice.vdencWeightsOffset) + 12 + 4 > end)
            return false;
        previousEnd = uint32_t(end);
    }

    BrcConstantData data {};
    memcpy(reinterpret_cast<uint8_t *>(&data) +
        offsetof(BrcConstantData, SLCSZ_THRDELTAI_U16),
        kConstantWords, sizeof(kConstantWords));
    memcpy(data.SADQPLambdaI, kSadLambdaI, sizeof(kSadLambdaI));
    memcpy(data.SADQPLambdaP, kSadLambdaP, sizeof(kSadLambdaP));
    memcpy(data.RDQPLambdaI, kRdLambdaI, sizeof(kRdLambdaI));
    memcpy(data.RDQPLambdaP, kRdLambdaP, sizeof(kRdLambdaP));
    memcpy(data.ModeCosts, params.inter ? kModeCostsPB : kModeCostsI,
        sizeof(kModeCostsI));
    for (uint32_t i = 0; i < params.sliceCount; ++i) {
        const auto &layout = params.slices[i];
        auto &slice = data.Slice[i];
        slice.SizeOfCMDs = uint16_t(layout.commandsBytes);
        slice.HcpWeightOffsetL0_StartInBytes = 0xffff;
        slice.HcpWeightOffsetL1_StartInBytes = 0xffff;
        slice.SliceState_StartInBytes = uint16_t(layout.sliceStateOffset);
        slice.SliceHeaderPIO_StartInBytes = uint16_t(layout.sliceHeaderOffset);
        slice.VdencWeightOffset_StartInBytes = uint16_t(layout.vdencWeightsOffset);
        slice.SliceHeader_SizeInBits = uint16_t(layout.sliceHeaderBits);
        slice.WeightTable_StartInBits = 0xffff;
        slice.WeightTable_EndInBits = 0xffff;
    }
    out = data;
    return true;
}
